def launch_training_task(
    dataset: torch.utils.data.Dataset,
    model: DiffusionTrainingModule,
    model_logger: ModelLogger,
    optimizer: torch.optim.Optimizer,
    scheduler: torch.optim.lr_scheduler.LRScheduler,
    num_workers: int = 8,
    save_steps: int = None,
    num_epochs: int = 1,
    gradient_accumulation_steps: int = 1,
    find_unused_parameters: bool = False,
):
    dataloader = torch.utils.data.DataLoader(dataset, shuffle=True, collate_fn=lambda x: x[0], num_workers=num_workers)
    accelerator = Accelerator(
        gradient_accumulation_steps=gradient_accumulation_steps,
        kwargs_handlers=[DistributedDataParallelKwargs(find_unused_parameters=find_unused_parameters)],
    )
    model, optimizer, dataloader, scheduler = accelerator.prepare(model, optimizer, dataloader, scheduler)
    writer = SummaryWriter(log_dir=f"{model_logger.output_path}/{datetime.now().strftime('%Y-%m-%d_%H:%M:%S')}")  # 指定日志目录
    global_step = 0  # 添加全局步数计数器

    it = tqdm(dataloader)
    for epoch_id in range(num_epochs):
        model_logger.on_epoch_start(accelerator, model, epoch_id)
        for data in it:
            with accelerator.accumulate(model):
                optimizer.zero_grad()
                loss = model(data)
                accelerator.backward(loss)
                optimizer.step()

                # 记录损失和学习率
                if accelerator.is_main_process:  # 只在主进程记录
                    writer.add_scalar("Loss/train", loss.detach().item(), global_step)
                    writer.add_scalar("Learning Rate", scheduler.get_last_lr()[0], global_step)
                global_step += 1
                model_logger.on_step_end(accelerator, model, save_steps)
                scheduler.step()
                it.set_description(f"loss={loss.detach().cpu().numpy().item()}")
        model_logger.on_epoch_end(accelerator, model, epoch_id)
    model_logger.on_training_end(accelerator, model, save_steps)


